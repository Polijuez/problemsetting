def load_init(problem_dir: Path) -> dict[str, Any]:
    """Read the generated ``init.yml``."""
    path = problem_dir / INIT_FILENAME
    if not path.is_file():
        raise CaseError(
            f"{path} not found -- init.yml, the cases it names and the committed "
            f"`*{CHECKSUM_SUFFIX}` checksums beside them are all build products of "
            f"meta.yml and generator.py; rebuild them with "
            f"`problemsetting regenerate {problem_dir.name}`"
        )
    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as error:
        raise CaseError(f"{path}: not valid YAML: {error}") from error
    if not isinstance(document, dict):
        raise CaseError(f"{path}: expected a mapping at the top level")
    return document


def _case_entries(document: dict[str, Any], source: str) -> list[dict[str, Any]]:
    """Every case mapping ``init.yml`` declares, flattened and validated, in order.

    One traversal of the emitted structure, so the two readers below --
    :func:`referenced_cases` (the archive's membership) and :func:`case_pairs`
    (``outputs``' work list) -- cannot disagree about what the file contains.  A
    hand-edited ``init.yml`` is the case both exist to catch, so a malformed entry
    is a ``CaseError`` naming the offending value rather than a case silently
    dropped from one list and not the other.
    """
    test_cases = document.get("test_cases")
    if not isinstance(test_cases, list) or not test_cases:
        raise CaseError(f"{source}: no test_cases -- run `problemsetting cases` first")
    entries: list[dict[str, Any]] = []
    for entry in test_cases:
        if not isinstance(entry, dict):
            raise CaseError(f"{source}: test_cases entries must be mappings, got {entry!r}")
        children = entry.get("batched")
        if children is None:
            children = [entry]
        if not isinstance(children, list):
            raise CaseError(f"{source}: `batched:` must be a list of cases")
        for child in children:
            if not isinstance(child, dict):
                raise CaseError(f"{source}: test case entries must be mappings, got {child!r}")
            entries.append(child)
    return entries


def _case_name(case: dict[str, Any], key: str, source: str) -> str | None:
    """One ``in:``/``out:`` value, or ``None`` when the case declares neither."""
    value = case.get(key)
    if value is None:
        return None
    if not isinstance(value, str):
        raise CaseError(f"{source}: `{key}:` must be a file name, got {value!r}")
    return value


def referenced_cases(document: dict[str, Any], source: str) -> list[str]:
    """Every ``in:``/``out:`` file ``init.yml`` names, in order, deduplicated.

    This is the archive's membership rule: a zip whose members are exactly the
    files the ``init.yml`` in the same directory references, so the two cannot
    drift apart.
    """
    names: list[str] = []
    for case in _case_entries(document, source):
        for key in ("in", "out"):
            if (name := _case_name(case, key, source)) is not None and name not in names:
                names.append(name)
    return names


def case_pairs(document: dict[str, Any], source: str) -> list[tuple[str | None, str]]:
    """Every ``(in, out)`` pair ``init.yml`` declares, in order, deduplicated by output.

    ``outputs`` runs one case per output file and needs the input that produced
    it; ``in`` is ``None`` for the output-only models, whose cases declare none
    (DMOJ supplies an empty sealed stdin, ``dmoj/problem.py:489-493``).  A repeated
    ``out`` -- a case selected by two subtasks -- is one expected output, so it is
    run once.
    """
    pairs: list[tuple[str | None, str]] = []
    seen: set[str] = set()
    for case in _case_entries(document, source):
        output = _case_name(case, "out", source)
        if output is None or output in seen:
            continue
        seen.add(output)
        pairs.append((_case_name(case, "in", source), output))
    return pairs


#: Fixed timestamp carried by every archive member: the ZIP epoch, 1980-01-01.
#: A real modification time is the one field that differs between two clones of
#: identical source, so pinning it is what makes the archive reproducible
#: (decision Q21; the plan's probe finding 3: ``ZipFile.write`` embeds the real
#: mtime, so two clones of one problem produced different archives).
ARCHIVE_DATE_TIME = (1980, 1, 1, 0, 0, 0)

#: Fixed Unix attributes for every member: a regular file with mode ``rw-r--r--``.
#: The alternative is the source file's own mode, which varies with the umask and
#: with how the checkout was made.
ARCHIVE_MEMBER_ATTR = 0o100644 << 16

#: Fixed deflate level.  ``zipfile``'s default (``-1``) means "whatever zlib's
#: default is", which is not a documented constant; naming the level makes the
#: archive bytes a function of the inputs alone.
ARCHIVE_COMPRESS_LEVEL = 9

#: Suffix of every committed checksum file (decision Q16).
CHECKSUM_SUFFIX = ".sha256sum"


def write_reproducible_zip(archive_path: Path, members: Sequence[tuple[str, Path]]) -> None:
    """Write ``(arcname, source)`` pairs as a zip that is byte-identical per input.

    Everything that would otherwise leak the build environment into the bytes is
    pinned (decision Q21):

    * each member's timestamp (:data:`ARCHIVE_DATE_TIME`, the ZIP epoch) --
      without this, a fresh clone's mtimes change the archive;
    * each member's attributes (:data:`ARCHIVE_MEMBER_ATTR`) -- otherwise the
      checkout's permissions show through;
    * the deflate level (:data:`ARCHIVE_COMPRESS_LEVEL`);
    * the member order, sorted by ``arcname``, so the caller's order (which comes
      from ``init.yml``) cannot leak into the bytes.

    ``ZipFile.write`` cannot be used for this: it takes the timestamp straight
    from the source file.  Members are streamed rather than buffered, because a
    case file can be megabytes and the archive is rebuilt wholesale on every run.
    """
    with zipfile.ZipFile(
        archive_path, "w", zipfile.ZIP_DEFLATED, compresslevel=ARCHIVE_COMPRESS_LEVEL
    ) as archive:
        for arcname, source in sorted(members, key=lambda member: member[0]):
            info = zipfile.ZipInfo(arcname, date_time=ARCHIVE_DATE_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.compress_level = ARCHIVE_COMPRESS_LEVEL
            info.create_system = 3  # Unix: the attributes above are a Unix mode.
            info.external_attr = ARCHIVE_MEMBER_ATTR
            info.file_size = source.stat().st_size
            with archive.open(info, "w") as destination, source.open("rb") as origin:
                shutil.copyfileobj(origin, destination, length=1 << 20)


def sha256_file(path: Path) -> str:
    """The SHA-256 of a file's bytes, as lowercase hexadecimal.

    Streamed by ``hashlib.file_digest`` rather than read whole: a case file can be
    megabytes, and this runs once per member on every archive.
    """
    with path.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def archive_checksum_name(archive_name: str) -> str:
    """The checksum of the archive bytes, named after the *declared* archive.

    Derived from ``init.yml``'s ``archive:`` value rather than a literal, so a
    problem whose archive is named anything else still gets a correctly named
    checksum beside it (decision Q15 and the plan's open item on
    ``test_cases.zip``).
    """
    return f"{archive_name}{CHECKSUM_SUFFIX}"


def case_data_checksum_name(archive_name: str) -> str:
    """The checksum of the case *data*, named after the declared archive."""
    return f"{archive_name}.cases{CHECKSUM_SUFFIX}"


def case_data_manifest(
    problem_dir: Path, names: Sequence[str], document: Mapping[str, Any]
) -> str:
    """A digest of the *case data*, not of how it was packaged.

    Files are listed first, one ``sha256sum`` line each, sorted by name, so the
    file verifies with ``sha256sum -c`` from the problem directory and is itself
    reproducible.

    The grading structure is appended as a ``#`` comment line: the points, batch
    membership and dependencies are part of what a generator produces, and a
    generator retuned only in *how it groups cases* leaves every case file -- and
    therefore the archive -- byte-identical, so neither checksum would move
    without this.  ``sha256sum -c`` ignores comment lines, so the file still
    verifies.  ``document`` is required rather than optional: the structure line
    is what gives this digest its teeth, so a caller cannot quietly produce a
    weaker one.

    The declared *archive filename* is excluded from the structure: it is how the
    case data is packaged, which is the one thing this second checksum exists to
    be independent of (decision Q15).
    """
    lines = [f"{sha256_file(problem_dir / name)}  {name}" for name in sorted(names)]
    structure = {key: value for key, value in document.items() if key != "archive"}
    # Canonical, sorted-key JSON: the manifest must not depend on PyYAML's mapping
    # order (it preserves insertion order, which is stable today but is not a
    # property this checksum should rely on).
    canonical = json.dumps(structure, sort_keys=True, separators=(",", ":"))
    lines.append(f"# {sha256_of(canonical)}  init.yml")
    return "".join(f"{line}\n" for line in lines)


def sha256_of(text: str) -> str:
    """The SHA-256 of a UTF-8 string's bytes."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def checksum_texts(
    problem_dir: Path, archive_name: str, names: Sequence[str], document: Mapping[str, Any]
) -> dict[str, str]:
    """Both committed checksums' *text*, keyed by file name, without writing them.

    Computing the text and writing it are separate steps so that a caller can ask
    what a build would commit *before* anything is committed.  That is what lets
    ``regenerate`` compare a rebuild against the committed checksums without ever
    overwriting one (decision Q22): the comparison needs the rebuilt digests, not
    the rebuilt *files*, and writing them first would replace the very record the
    comparison is about.
    """
    return {
        archive_checksum_name(archive_name): (
            f"{sha256_file(problem_dir / archive_name)}  {archive_name}\n"
        ),
        case_data_checksum_name(archive_name): case_data_manifest(
            problem_dir, names, document
        ),
    }


def measure_checksums(problem_dir: Path) -> dict[str, str]:
    """The checksums the problem on disk currently produces, computed but not written.

    Read back through :func:`load_init`, exactly like :func:`run_archive`: the
    archive name and the case membership come from the emitted ``init.yml``, so the
    measured digests describe the build that is actually there rather than what
    some earlier call happened to pass around.
    """
    init_path = problem_dir / INIT_FILENAME
    document = load_init(problem_dir)
    archive_name = declared_archive(document, str(init_path))
    names = referenced_cases(document, str(init_path))
    return checksum_texts(problem_dir, archive_name, names, document)


def write_checksums(problem_dir: Path, texts: Mapping[str, str]) -> dict[str, Path]:
    """Write the committed checksums beside the archive; return their paths by name.

    The first ties the packaged artifact to the committed source; the second
    records the cases independently of how they were packaged (decision Q15).

    Written only after a successful archive build, so each describes the last
    *successful* build.  A later failure that discards the archive -- ``outputs``
    removes it whenever a rebuild breaks, because DMOJ reads answers out of it --
    therefore leaves these two files describing the archive that used to be
    there.  That is deliberate: they are the committed record of what the
    generator produced, and deleting them on a failure would lose the evidence
    ``regenerate --check`` (decision Q22) compares against.

    Keyed by file name rather than returned positionally: the two names are
    derived from the archive name, and a caller reporting "sha256 of the archive"
    against the case-data file would be wrong in a way nothing else would notice.
    """
    written = {name: problem_dir / name for name in sorted(texts)}
    for name, text in texts.items():
        written[name].write_text(text, encoding="utf-8")
    return written


def declared_archive(document: Mapping[str, Any], source: str) -> str:
    """The ``archive:`` filename ``init.yml`` declares, or an error naming ``source``."""
    archive_name = document.get("archive")
    if not isinstance(archive_name, str) or not archive_name:
        raise CaseError(
            f"{source}: no `archive:` filename declared; the judge needs one to find "
            f"the bundled cases"
        )
    return archive_name


def run_archive(problem: str, *, commit: bool = True) -> int:
    """Zip the cases ``init.yml`` references; write the checksums unless told not to.

    ``commit=False`` is what ``regenerate`` uses: the archive itself must be
    rebuilt (the judge reads the expected answers out of it), but the checksum
    *files* are the committed record ``regenerate`` compares against, so a build
    that wrote them first would destroy the evidence before the comparison.
    """
    problem_dir = judges.resolve_problem(problem)
    init_path = problem_dir / INIT_FILENAME
    document = load_init(problem_dir)
    archive_name = declared_archive(document, str(init_path))
    names = referenced_cases(document, str(init_path))

    missing = [name for name in names if not (problem_dir / name).is_file()]
    if missing:
        # A zip missing expected outputs would be graded as if those cases had
        # no answer at all, so refuse rather than ship a half archive.
        raise CaseError(
            f"{len(missing)} file(s) referenced by {init_path} are missing, e.g. "
            f"{missing[0]}; run `problemsetting outputs {problem_dir.name}` (or "
            f"`problemsetting build {problem_dir.name}`) after generating cases"
        )

    archive_path = problem_dir / archive_name
    write_reproducible_zip(archive_path, [(name, problem_dir / name) for name in names])
    print(f"{archive_path}: {len(names)} members")
    if not commit:
        return 0
    written = write_checksums(
        problem_dir, checksum_texts(problem_dir, archive_name, names, document)
    )
    print(f"{written[archive_checksum_name(archive_name)]}: sha256 of the archive")
    print(f"{written[case_data_checksum_name(archive_name)]}: sha256 of the case data")
    return 0


