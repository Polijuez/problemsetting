@dataclasses.dataclass(frozen=True)
class CaseFile:
    """Where one case's files live, relative to the problem directory."""

    index: int
    has_input: bool

    @property
    def input_name(self) -> str | None:
        return f"{CASES_DIRNAME}/{self.index}.in" if self.has_input else None

    @property
    def output_name(self) -> str:
        return f"{CASES_DIRNAME}/{self.index}.out"


def write_case_files(
    problem_dir: Path, cases: Sequence[Any], *, has_input: bool, source: str
) -> tuple[list[CaseFile], list[str]]:
    """Write each case's input; return its file names and the outputs invalidated.

    Expected outputs are *not* produced here: they are ``outputs``' job (ticket
    03), because they require running the model solution.  But an input that
    *changed* invalidates its sibling ``.out``, which is deleted so that the pair
    cannot silently disagree.  A stale ``.out`` is the one failure mode this
    toolkit must never ship, because the judge would grade it as the expected
    answer.  An input that is byte-identical is left alone, so re-running with no
    change keeps every output.

    ``write_file`` is author code like the other hooks, so a failure is reported
    with the case index rather than escaping as a traceback.
    """
    cases_dir = problem_dir / CASES_DIRNAME
    cases_dir.mkdir(exist_ok=True)
    files: list[CaseFile] = []
    invalidated: list[str] = []
    for index, case in enumerate(cases):
        case_file = CaseFile(index, has_input)
        if case_file.input_name is not None:
            text = _render_input(case, index, source)
            path = problem_dir / case_file.input_name
            if _read_text(path) != text:
                path.write_text(text, encoding="utf-8")
                if (output := problem_dir / case_file.output_name).is_file():
                    output.unlink()
                    invalidated.append(case_file.output_name)
        files.append(case_file)
    _prune_case_files(cases_dir, len(cases))
    return files, invalidated


def _render_input(case: Any, index: int, source: str) -> str:
    buffer = io.StringIO()
    try:
        case.write_file(buffer)
    except Exception as error:
        raise CaseError(f"{source}: write_file() failed for case {index}: {error}") from error
    return buffer.getvalue()


def _read_text(path: Path) -> str | None:
    """The file's text, or None when it does not exist (or is not readable as text)."""
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _prune_case_files(cases_dir: Path, count: int) -> list[str]:
    """Remove ``cases/{i}.in``/``.out`` left over from a larger previous run."""
    removed: list[str] = []
    for path in sorted(cases_dir.iterdir()):
        match = _CASE_FILE_RE.match(path.name)
        if match and int(match.group(1)) >= count and path.is_file():
            path.unlink()
            removed.append(f"{CASES_DIRNAME}/{path.name}")
    return removed


def require_model_files(problem_dir: Path, resolved: meta_mod.ResolvedMeta) -> list[str]:
    """Check the files ``init.yml`` will name actually exist; return their names."""
    required: list[str] = []
    if resolved.uses_checker:
        required.append(CHECKER_FILENAME)
    if resolved.uses_signature:
        required.extend((SIGNATURE_ENTRY, SIGNATURE_HEADER))
    for name in required:
        if not (problem_dir / name).is_file():
            raise CaseError(
                f"{problem_dir / name} not found: model {resolved.model!r} grades with "
                f"{_because(name)}"
            )
    return required


def _because(name: str) -> str:
    if name == CHECKER_FILENAME:
        return "a custom checker, and `init.yml` will declare `checker: checker.py`"
    if name == SIGNATURE_HEADER:
        return (
            "DMOJ's signature grader, and `init.yml` will declare "
            "`signature_grader: {entry: evaluator.cpp, header: signature.hpp}`"
        )
    return "DMOJ's signature grader, which compiles `evaluator.cpp` against the submission"


def _points_text(points: int | float) -> str:
    """YAML text for a points value, through PyYAML's own scalar emitter.

    ``f"{points:g}"`` would round (``100/3`` becomes ``33.3333``) and would emit
    ``1e+21``, which YAML reads back as a *string*.  The emitter round-trips both
    and is the same code that reads the file.
    """
    return yaml.safe_dump(points, default_flow_style=True).split("\n", 1)[0]


def _case_entry(case_file: CaseFile) -> str:
    pairs = []
    if case_file.input_name is not None:
        pairs.append(f"in: {case_file.input_name}")
    pairs.append(f"out: {case_file.output_name}")
    return "- {" + ", ".join(pairs) + "}"


def render_init(
    problem_name: str,
    resolved: meta_mod.ResolvedMeta,
    subtasks: Sequence[Subtask],
    membership: Sequence[Sequence[int]],
    case_files: Sequence[CaseFile],
) -> str:
    """Render the ``init.yml`` the judge loads.

    Driven by the resolved axes, never by the model *name*: ``checker:`` appears
    exactly when the checker axis is custom and ``signature_grader:`` exactly
    when the grader axis is signature (``dmoj/problem.py:200-210`` picks a
    grader by those keys, and by nothing else).
    """
    lines = [INIT_HEADER, f"archive: {problem_name}.zip"]
    if resolved.uses_checker:
        lines.append(f"checker: {CHECKER_FILENAME}")
    if resolved.uses_signature:
        lines.append(
            f"signature_grader: {{entry: {SIGNATURE_ENTRY}, header: {SIGNATURE_HEADER}}}"
        )
    lines.append("test_cases:")
    for subtask, indices in zip(subtasks, membership, strict=True):
        lines.append(f"- points: {_points_text(subtask.points)}")
        lines.append("  batched:")
        lines.extend(f"  {_case_entry(case_files[index])}" for index in indices)
        if subtask.dependencies:
            joined = ", ".join(str(dependency) for dependency in subtask.dependencies)
            lines.append(f"  dependencies: [{joined}]")
    return "\n".join(lines) + "\n"


