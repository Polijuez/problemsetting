"""``cases``, ``archive`` and ``build``: generator → ``cases/*.in`` + ``init.yml`` → ``.zip``.

The generator is the author's code (``<problem>/generator.py``); this module is
the fixed half of the contract (decision Q22).  The protocol:

* ``TestCase.check()`` / ``TestCase.write_file(f)`` -- the case validates itself
  and writes its own input format.  The *toolkit* chooses file names.
* ``Generator.get_cases()`` -- the ordered case list.  Position is file number:
  case ``i`` is ``cases/{i}.in`` / ``cases/{i}.out``.
* ``Generator.get_subtasks()`` -- ``(points, check_fn)`` per subtask, with an
  optional third element: a list of 1-based prerequisite batch numbers, which
  becomes DMOJ's per-batch ``dependencies:`` key.  Two-element tuples keep
  working unchanged.

A case belongs to a subtask when ``check_fn(case)`` is truthy, so a case may be
in several batches -- that is the "all-accepting final subtask" convention the
``standard``/``batched`` templates rely on.

Two things the emitted ``init.yml`` gets from ``meta.yml`` instead of from the
generator (both are properties of the *model*, resolved by :mod:`meta`):

* ``submission: text`` models (the two output-only ones) have **no input**:
  DMOJ's ``TestCase._make_input_data_io()`` falls back to a sealed empty
  ``MemoryIO`` when a case declares no ``in:`` (``dmoj/problem.py:489-493``), so
  those cases declare only ``out:`` and their ``write_file`` is never called.
* a custom-checker model needs ``checker.py`` on disk, and a signature model
  needs ``evaluator.cpp`` + ``signature.hpp``; both are named in ``init.yml``
  and both are checked here, so a dangling reference is an authoring error
  instead of a judge-side failure inside the container.

Batches are validated the way DMOJ validates them
(``dmoj/problem.py:325-337``): dependencies must be positive integers strictly
less than the batch number that declares them, nested batches are rejected
outright (``InvalidInitException('nested batches')``), and a batch that selects
no case is refused here because an empty ``batched:`` key is YAML ``null`` and
the judge iterates that value.
"""

