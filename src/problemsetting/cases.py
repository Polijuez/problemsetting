def add_archive_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("problem", help="problem directory whose init.yml declares the archive")


def run_archive_command(args: argparse.Namespace) -> int:
    return run_archive(args.problem)


def load_init(problem_dir: Path) -> dict[str, Any]:
    """Read the generated ``init.yml``."""
    path = problem_dir / INIT_FILENAME
    if not path.is_file():
        raise CaseError(
            f"{path} not found -- init.yml is generated; run "
            f"`problemsetting cases {problem_dir.name}` first"
        )
    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as error:
        raise CaseError(f"{path}: not valid YAML: {error}") from error
    if not isinstance(document, dict):
        raise CaseError(f"{path}: expected a mapping at the top level")
    return document


def referenced_cases(document: dict[str, Any], source: str) -> list[str]:
    """Every ``in:``/``out:`` file ``init.yml`` names, in order, deduplicated.

    This is the archive's membership rule: a zip whose members are exactly the
    files the ``init.yml`` in the same directory references, so the two cannot
    drift apart.
    """
    test_cases = document.get("test_cases")
    if not isinstance(test_cases, list) or not test_cases:
        raise CaseError(f"{source}: no test_cases -- run `problemsetting cases` first")
    names: list[str] = []
    for entry in test_cases:
        if not isinstance(entry, dict):
            raise CaseError(f"{source}: test_cases entries must be mappings, got {entry!r}")
        children = entry.get("batched")
        if children is None:
            children = [entry]
        if not isinstance(children, list):
            raise CaseError(f"{source}: `batched:` must be a list of cases")
        for child in children:
            if not isinstance(child, dict):
                raise CaseError(f"{source}: test case entries must be mappings, got {child!r}")
            for key in ("in", "out"):
                value = child.get(key)
                if value is None:
                    continue
                if not isinstance(value, str):
                    raise CaseError(f"{source}: `{key}:` must be a file name, got {value!r}")
                if value not in names:
                    names.append(value)
    return names


def run_archive(problem: str) -> int:
    problem_dir = Path.cwd() / problem
    init_path = problem_dir / INIT_FILENAME
    document = load_init(problem_dir)
    archive_name = document.get("archive")
    if not isinstance(archive_name, str) or not archive_name:
        raise CaseError(
            f"{init_path}: no `archive:` filename declared; the judge needs one to find "
            f"the bundled cases"
        )
    names = referenced_cases(document, str(init_path))

    missing = [name for name in names if not (problem_dir / name).is_file()]
    if missing:
        # A zip missing expected outputs would be graded as if those cases had
        # no answer at all, so refuse rather than ship a half archive.
        raise CaseError(
            f"{len(missing)} file(s) referenced by {init_path} are missing, e.g. "
            f"{missing[0]}; run `problemsetting outputs {problem_dir.name}` (or "
            f"`problemsetting build {problem_dir.name}`) after generating cases"
        )

    archive_path = problem_dir / archive_name
    with zipfile.ZipFile(archive_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in names:
            archive.write(problem_dir / name, arcname=name)
    print(f"{archive_path}: {len(names)} members")
    return 0


