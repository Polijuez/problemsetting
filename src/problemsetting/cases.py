def add_cases_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("problem", help="problem directory to build cases for")
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="seed for the generator (default: the generator's own)",
    )


def run(args: argparse.Namespace) -> int:
    return run_cases(args.problem, seed=args.seed)


def run_cases(problem: str, *, seed: int | None = None) -> int:
    problem_dir = Path.cwd() / problem
    # meta.yml first: the model decides whether cases even have input files.
    _, resolved = meta_mod.load(problem_dir)

    generator = load_generator(problem_dir, seed)
    source = str(problem_dir / GENERATOR_FILENAME)
    cases = read_cases(generator, source)
    subtasks = read_subtasks(generator, source)
    _check_model_supports(subtasks, resolved, problem_dir)

    # Classify before writing anything: a bad classifier must not leave a
    # half-written cases/ directory behind.
    membership = classify(subtasks, cases, source)
    case_files, invalidated = write_case_files(
        problem_dir, cases, has_input=not resolved.is_output_only, source=source
    )
    links = require_model_files(problem_dir, resolved)

    init = render_init(problem_dir.name, resolved, subtasks, membership, case_files)
    init_path = problem_dir / INIT_FILENAME
    init_path.write_text(init, encoding="utf-8")

    written = sum(1 for case_file in case_files if case_file.input_name is not None)
    print(f"{problem_dir.name}: {len(case_files)} cases, {written} input files -> {CASES_DIRNAME}/")
    for subtask, indices in zip(subtasks, membership, strict=True):
        detail = f"batch {subtask.number}: {_points_text(subtask.points)} pts, {len(indices)} cases"
        if subtask.dependencies:
            detail += f", after {', '.join(str(d) for d in subtask.dependencies)}"
        print(f"  {detail}")
    if links:
        print(f"  {', '.join(links)}")
    if invalidated:
        print(
            f"  discarded {len(invalidated)} stale expected output(s) whose input "
            f"changed: {', '.join(invalidated[:3])}"
            + (", ..." if len(invalidated) > 3 else "")
        )
    print(f"wrote {init_path}")
    return 0


def _check_model_supports(
    subtasks: Sequence[Subtask], resolved: meta_mod.ResolvedMeta, problem_dir: Path
) -> None:
    """Reject a generator whose batch structure contradicts its model.

    ``batch: single`` models pay once, all-or-nothing.  Several subtasks from
    such a generator still produce valid YAML -- several sibling batches -- which
    is the dangerous outcome: the file loads, and the scoring is silently no
    longer what the model says it is.
    """
    if len(subtasks) > 1 and not resolved.is_batched:
        numbers = ", ".join(str(subtask.number) for subtask in subtasks)
        raise CaseError(
            f"{problem_dir}: model {resolved.model!r} grades as a single batch, but "
            f"get_subtasks() returned {len(subtasks)} subtasks ({numbers}); emitting "
            f"them would turn an all-or-nothing problem into partial scoring without "
            f"saying so.  Use the 'batched' model (or `batch: subtasks` in meta.yml) "
            f"if partial scoring is intended"
        )


