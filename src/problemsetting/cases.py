GENERATOR_FILENAME = "generator.py"
INIT_FILENAME = "init.yml"
CASES_DIRNAME = "cases"

#: The standard checker/signature file names (ticket 11 fixes these names; the
#: judge accepts others, but a problem that renames them must be checked here
#: rather than emitting a reference to a file that does not exist).
CHECKER_FILENAME = "checker.py"
SIGNATURE_HEADER = "signature.hpp"
SIGNATURE_ENTRY = "evaluator.cpp"

#: First line of every generated ``init.yml``.  It is a build artifact: the
#: sources of truth are ``meta.yml`` (model/limits) and ``generator.py`` (cases).
INIT_HEADER = (
    "# Generated by `problemsetting cases` -- edit meta.yml and generator.py, not this file."
)

#: Leftover case files from a previous, larger run are removed: a stale
#: ``cases/{i}.out`` is the one failure mode this toolkit must never leave
#: behind, because the judge would grade it as the expected answer.
_CASE_FILE_RE = re.compile(r"(\d+)\.(?:in|out)\Z")


class GeneratorLike(Protocol):
    """The slice of the author's ``Generator`` this module calls.

    Structural, not inherited: a generator is author code loaded from a file, so
    there is no base class to subclass and nothing to enforce at runtime -- only
    the two calls below, which :func:`load_generator` and :func:`read_cases` /
    :func:`read_subtasks` check for by hand.
    """

    def get_cases(self) -> Sequence[Any]: ...

    def get_subtasks(self) -> Sequence[Any]: ...


# ---------------------------------------------------------------------------
# The generator: loading it, and reading the protocol out of it
# ---------------------------------------------------------------------------


def load_generator(problem_dir: Path, seed: int | None = None) -> GeneratorLike:
    """Compile and run ``<problem_dir>/generator.py``; instantiate its ``Generator``.

    The file is *compiled from source each time*, never imported through
    ``importlib``'s file loader: that loader honours a sibling ``__pycache__``
    entry whenever the bytecode's recorded (mtime, size) still matches, so a
    same-second, same-length edit would silently run the previous generator --
    and the cases would then be built from code the author is no longer looking
    at.  Compiling costs nothing at this scale and removes the whole class of
    "why did my change not apply" bugs.
    """
    path = problem_dir / GENERATOR_FILENAME
    if not path.is_file():
        raise CaseError(
            f"{path} not found -- every problem needs a generator.py; the model "
            f"template ships a complete one to start from"
        )
    try:
        code = compile(path.read_text(encoding="utf-8"), str(path), "exec")
    except (OSError, UnicodeDecodeError, SyntaxError) as error:
        raise CaseError(f"{path}: {error}") from error

    module = types.ModuleType(f"_problemsetting_generator_{problem_dir.name}")
    module.__file__ = str(path)
    try:
        exec(code, module.__dict__)
    except Exception as error:  # author code: report it without the traceback
        raise CaseError(f"{path}: {error}") from error

    factory = getattr(module, "Generator", None)
    if factory is None:
        raise CaseError(
            f"{path}: no `Generator` class -- the toolkit instantiates "
            f"`Generator()` and calls `get_cases()` and `get_subtasks()` on it"
        )
    try:
        return factory() if seed is None else factory(seed)
    except Exception as error:
        raise CaseError(f"{path}: Generator(...) failed: {error}") from error


@dataclasses.dataclass(frozen=True)
class Subtask:
    """One entry of ``Generator.get_subtasks()`` after validation."""

    #: 1-based batch number, i.e. the order in ``get_subtasks()``.
    number: int
    points: int | float
    check: Callable[[Any], Any]
    #: Prerequisite batch numbers; empty when the subtask declares none.
    dependencies: tuple[int, ...]


def require_sequence(value: Any, source: str, expectation: str) -> Sequence[Any]:
    """Check ``value`` is a list-shaped result; ``expectation`` names what it should be.

    ``str``/``bytes`` are sequences too, and a generator that returns
    ``"cases"`` by mistake would otherwise be read as three one-character cases.
    """
    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
        raise CaseError(f"{source}: {expectation}, not {type(value).__name__}")
    return value


def read_cases(generator: GeneratorLike, source: str) -> list[Any]:
    """``generator.get_cases()``, validated as a non-empty ordered sequence."""
    try:
        cases = generator.get_cases()
    except Exception as error:  # the author's ``check()`` runs here
        raise CaseError(f"{source}: get_cases() failed: {error}") from error
    require_sequence(cases, source, "get_cases() must return a list of cases")
    if not cases:
        raise CaseError(f"{source}: get_cases() returned no cases; there is nothing to grade")
    for index, case in enumerate(cases):
        for method in ("check", "write_file"):
            if not callable(getattr(case, method, None)):
                raise CaseError(
                    f"{source}: case {index} ({type(case).__name__}) has no "
                    f"{method}() method; the toolkit only requires those two"
                )
    return list(cases)


def read_subtasks(generator: GeneratorLike, source: str) -> list[Subtask]:
    """``generator.get_subtasks()``, validated against DMOJ's batch rules.

    Every rule here exists because the alternative is an ``init.yml`` the judge
    rejects at load time with a message about the file's shape rather than about
    the generator line that caused it.
    """
    try:
        entries = generator.get_subtasks()
    except Exception as error:
        raise CaseError(f"{source}: get_subtasks() failed: {error}") from error
    require_sequence(entries, source, "get_subtasks() must return a list of (points, check) entries")
    if not entries:
        raise CaseError(
            f"{source}: get_subtasks() returned nothing; a problem with no subtasks "
            f"has nothing to grade"
        )

    subtasks: list[Subtask] = []
    for index, entry in enumerate(entries, start=1):
        subtasks.append(_read_subtask(entry, index, source, len(entries)))
    return subtasks


def _read_subtask(entry: Any, number: int, source: str, total: int) -> Subtask:
    where = f"subtask {number} of {total}" if total > 1 else "the subtask"
    require_sequence(entry, source, f"{where} must be a (points, check) pair")
    if len(entry) not in (2, 3):
        raise CaseError(
            f"{source}: {where} has {len(entry)} elements; expected (points, check) "
            f"or (points, check, dependencies)"
        )
    if not isinstance(entry[1], Callable):
        if isinstance(entry[1], (list, tuple)):
            # The shape this rejects: (points, [inner, batches]).
            raise CaseError(
                f"{source}: {where} holds a nested subtask list where the classifier "
                f"should be; DMOJ rejects nested batches ('nested batches'), so "
                f"subtasks must be a flat list of (points, check) pairs"
            )
        raise CaseError(
            f"{source}: {where} has a non-callable classifier ({entry[1]!r}); the second "
            f"element is `check_fn(case)`, called once per case"
        )

    points = entry[0]
    if isinstance(points, bool) or not isinstance(points, (int, float)):
        raise CaseError(
            f"{source}: {where} has non-numeric points ({points!r}); points are the "
            f"batch's share of the score"
        )
    if points <= 0:
        raise CaseError(
            f"{source}: {where} is worth {points} points; a batch worth no points can "
            f"never score"
        )

    dependencies = _read_dependencies(entry[2] if len(entry) == 3 else [], number, where, source)
    return Subtask(number, points, entry[1], dependencies)


def _read_dependencies(raw: Any, number: int, where: str, source: str) -> tuple[int, ...]:
    if raw is None:
        return ()
    require_sequence(
        raw,
        source,
        f"{where} declares dependencies {raw!r}; the third element must be a "
        f"list of 1-based batch numbers, e.g. [1]",
    )
    dependencies: list[int] = []
    for value in raw:
        if isinstance(value, bool) or not isinstance(value, int):
            raise CaseError(
                f"{source}: {where} declares dependency {value!r}; dependencies must be "
                f"positive integers naming earlier batches"
            )
        if value < 1:
            raise CaseError(
                f"{source}: {where} depends on batch {value}; DMOJ requires batches to "
                f"be positive integers ('dependencies must be positive integers')"
            )
        if value >= number:
            raise CaseError(
                f"{source}: {where} depends on batch {value}, which is not an earlier "
                f"batch; DMOJ requires each dependency to be less than the batch that "
                f"declares it ('dependencies depends on non-earlier batch')"
            )
        dependencies.append(value)
    # Sorted and deduplicated: the judge compares dependencies as a set, so this
    # only makes the emitted file canonical.
    return tuple(sorted(set(dependencies)))


def classify(subtasks: Iterable[Subtask], cases: Sequence[Any], source: str) -> list[list[int]]:
    """Case indices per subtask, in case order.

    Two rules, both of which exist because the alternative is an ``init.yml``
    the judge chokes on at load time instead of an error naming the generator:

    * ``check_fn`` is author code, so a classifier that raises is reported with
      the batch and the case it raised on;
    * a batch that selects no case is refused.  DMOJ branches on
      ``'batched' in case_config`` and then iterates the value
      (``dmoj/problem.py:227-235``), so an empty ``batched:`` key -- YAML
      ``null`` -- fails with ``TypeError: 'NoneType' object is not iterable``.
    """
    cases = list(cases)
    membership: list[list[int]] = []
    for subtask in subtasks:
        selected: list[int] = []
        for index, case in enumerate(cases):
            try:
                matched = subtask.check(case)
            except Exception as error:
                raise CaseError(
                    f"{source}: the classifier of batch {subtask.number} raised on case "
                    f"{index}: {error}"
                ) from error
            if matched:
                selected.append(index)
        if not selected:
            raise CaseError(
                f"{source}: the classifier of batch {subtask.number} selects none of the "
                f"{len(cases)} cases; a batch with no cases cannot be emitted (DMOJ would "
                f"fail to load the problem).  Every batch needs at least one case -- the "
                f"usual shape is an all-accepting last batch that absorbs the rest"
            )
        membership.append(selected)
    return membership


